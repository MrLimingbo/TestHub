'use strict'
const assert = require('node:assert/strict')
const test = require('node:test')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { prepareUpgrade, commitUpgrade, recoverUpgrade, writeMarker, digest } = require('../app/src/workspace-upgrade.cjs')
async function fixture(t) {
  const parent = await fs.mkdtemp(path.join(os.tmpdir(), 'testhub-upgrade-'))
  t.after(() => fs.rm(parent, { recursive: true, force: true }))
  const directory = path.join(parent, 'local-workspace'), backend = path.join(parent, 'backend.jar')
  await fs.mkdir(path.join(directory, 'objects'), { recursive: true })
  await fs.writeFile(path.join(directory, 'workspace.mv.db'), 'old database')
  await fs.writeFile(path.join(directory, 'workspace-secrets.enc'), 'os encrypted secrets')
  await fs.writeFile(path.join(directory, 'objects', 'attachment'), 'old attachment')
  await fs.writeFile(backend, 'new binary')
  return { parent, directory, backend }
}
test('first upgraded startup snapshots existing data and only a successful startup records the new binary', async t => {
  const { parent, directory, backend } = await fixture(t)
  const upgrade = await prepareUpgrade(directory, backend)
  assert.equal(await fs.readFile(path.join(upgrade.snapshot, 'workspace.mv.db'), 'utf8'), 'old database')
  assert.equal(await fs.readFile(path.join(upgrade.snapshot, 'objects', 'attachment'), 'utf8'), 'old attachment')
  assert.equal(await fs.readFile(path.join(upgrade.snapshot, 'workspace-secrets.enc'), 'utf8'), 'os encrypted secrets')
  await fs.writeFile(path.join(directory, 'workspace.mv.db'), 'migrated database')
  await commitUpgrade(upgrade)
  assert.equal(await recoverUpgrade(directory), false)
  assert.equal((await prepareUpgrade(directory, backend)).snapshot, undefined)
  assert.equal((await fs.readdir(parent)).filter(name => name.startsWith('workspace-before-upgrade-')).length, 1)
})
test('unchanged binary does not create repeated snapshots; a new binary does', async t => {
  const { directory, backend } = await fixture(t)
  await writeMarker(directory, await digest(backend))
  assert.equal((await prepareUpgrade(directory, backend)).snapshot, undefined)
  await fs.writeFile(backend, 'next binary')
  assert.ok((await prepareUpgrade(directory, backend)).snapshot)
})
for (const stage of ['before-mutation', 'migration', 'first-rollback-rename', 'second-rollback-rename']) test(`interrupted upgrade recovers original data at ${stage}`, async t => {
  const { parent, directory, backend } = await fixture(t)
  const upgrade = await prepareUpgrade(directory, backend)
  if (stage !== 'before-mutation') await fs.writeFile(path.join(directory, 'workspace.mv.db'), 'partially migrated database')
  const journal = JSON.parse(await fs.readFile(directory + '.upgrade.json', 'utf8'))
  if (stage.includes('rollback-rename')) await fs.rename(directory, path.join(parent, journal.failed))
  if (stage === 'second-rollback-rename') await fs.rename(upgrade.snapshot, directory)
  assert.equal(await recoverUpgrade(directory), true)
  assert.equal(await fs.readFile(path.join(directory, 'workspace.mv.db'), 'utf8'), 'old database')
  assert.equal(await fs.readFile(path.join(directory, 'objects', 'attachment'), 'utf8'), 'old attachment')
  assert.equal(await recoverUpgrade(directory), false)
})
test('invalid upgrade record cannot move data outside the workspace', async t => {
  const { directory } = await fixture(t)
  await fs.writeFile(directory + '.upgrade.json', JSON.stringify({ version: 1, snapshot: '../outside', failed: 'bad' }))
  await assert.rejects(recoverUpgrade(directory), /无效/)
  assert.equal(await fs.readFile(path.join(directory, 'workspace.mv.db'), 'utf8'), 'old database')
})
